const translations = { fr, en };

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: typeof fr } | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem("bekon-lang");
    return stored === "en" ? "en" : "fr";
  });
  const setLang = (l: Lang) => {
    localStorage.setItem("bekon-lang", l);
    setLangState(l);
  };
  return <LangContext.Provider value={{ lang, setLang, t: translations[lang] }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}
